import type {
  LinearProjectFieldSnapshot,
  LinearProjectRef,
  LinearProjectTargetRequest,
  LinearProjectUpdateHealth,
  LinearProjectUpdateNode
} from './project-agent-access'

export const LINEAR_PROJECT_UPDATE_HEALTH_CLI_VALUES = ['on-track', 'at-risk', 'off-track'] as const
export type LinearProjectUpdateHealthInput =
  (typeof LINEAR_PROJECT_UPDATE_HEALTH_CLI_VALUES)[number]

const HEALTH_BY_CLI_VALUE: Record<LinearProjectUpdateHealthInput, LinearProjectUpdateHealth> = {
  'on-track': 'onTrack',
  'at-risk': 'atRisk',
  'off-track': 'offTrack'
}

/** Returns null for anything else, including the camelCase API spellings. */
export function toLinearProjectUpdateHealth(value: string): LinearProjectUpdateHealth | null {
  return HEALTH_BY_CLI_VALUE[value as LinearProjectUpdateHealthInput] ?? null
}

export type LinearProjectUpdateAddRequest = LinearProjectTargetRequest & {
  body: string
  health?: LinearProjectUpdateHealth
  isDiffHidden?: boolean
  writeId?: string
}

/** References stay as user inputs on the wire; the host that owns the token resolves them. */
export type LinearProjectCreateRequest = {
  name: string
  teams: string[]
  description?: string
  content?: string
  status?: string
  lead?: string
  members?: string[]
  labels?: string[]
  priority?: number
  startDate?: string
  targetDate?: string
  color?: string
  icon?: string
  writeId?: string
  workspaceId?: string
}

export type LinearProjectCreateResult = {
  project: LinearProjectRef
  meta: {
    workspaceId: string
    /** Always a UUID v4; generated by the host when the caller did not pin one. */
    writeId: string
    deduplicated: boolean
  }
}

export type LinearProjectUpdateAddResult = {
  projectUpdate: Pick<LinearProjectUpdateNode, 'id' | 'url' | 'health' | 'createdAt'>
  project: LinearProjectRef
  meta: {
    workspaceId: string
    bodyChars: number
    writeId: string
    /** True when a pinned write id matched an existing post with the same intent. */
    deduplicated: boolean
  }
}

export const LINEAR_PROJECT_EDITABLE_FIELDS = [
  'name',
  'description',
  'content',
  'status',
  'lead',
  'members',
  'teams',
  'labels',
  'priority',
  'startDate',
  'targetDate',
  'color',
  'icon'
] as const
export type LinearProjectEditableField = (typeof LINEAR_PROJECT_EDITABLE_FIELDS)[number]

/**
 * Only the keys present were requested. `description` clears to `''`; `content`,
 * `lead`, the dates and `icon` clear to `null`; `members` and `labels` clear to
 * `[]`. `status` and `color` are non-null on `Project` and have no clear form,
 * and a team replacement may never be empty.
 */
export type LinearProjectEditRequest = LinearProjectTargetRequest & {
  name?: string
  description?: string
  content?: string | null
  status?: string
  lead?: string | null
  members?: string[]
  teams?: string[]
  labels?: string[]
  priority?: number
  startDate?: string | null
  targetDate?: string | null
  color?: string
  icon?: string | null
}

export type LinearProjectEditResult = {
  project: LinearProjectRef
  /** Only fields whose value actually changed, in LINEAR_PROJECT_EDITABLE_FIELDS order. */
  changed: LinearProjectEditableField[]
  previous: Partial<LinearProjectFieldSnapshot>
  current: Partial<LinearProjectFieldSnapshot>
  /** `noop` means every requested field already held the requested value; no mutation ran. */
  meta: { workspaceId: string; noop: boolean }
}
